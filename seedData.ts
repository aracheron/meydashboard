export function generateInitialSalesData(referenceDate = getTodayDateString()): SaleRecord[] {
  return RAW_SEED_SALES.map((row, index) => {
    const id = `SALE-${String(RAW_SEED_SALES.length - index).padStart(4, '0')}`;
    const date = shiftDateString(referenceDate, -row.daysAgo);
    return {
      id,
      date,
      buyerName: row.buyerName,
      item: row.item,
      quantity: row.quantity,
      unitPrice: row.unitPrice,
      total: calculateSaleTotal(row.quantity, row.unitPrice),
      channel: row.channel,
      paymentStatus: row.paymentStatus,
      notes: row.notes || '',
    };
  });
}

